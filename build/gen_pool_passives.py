# -*- coding: utf-8 -*-
"""The three stage passives: everything the mod grants hangs off these.

The pool used to be twelve passives, one per character level, applied by an
Osiris rule that read GetLevel and picked the right one. No add-on mod can run
Osiris (see gen_meta.py), so that whole mechanism was dead code that never once
executed. It is replaced here by something simpler and, I think, better in its
own right: the pool follows your *cultivation stage*, not your adventuring level.

    Cultivator          8 Essence      nine Initiate paths
    + Foundation       16 Essence      nine Adept paths
    + Golden Core      24 Essence      nine Master paths

Those are the same three numbers the level curve reached at its caps - the old
`pool_for()` gave 8 at the level-4 cap, 16 at the level-8 cap and 24 at 12 - so
a full cultivator is exactly as strong as before. What changes is that power now
comes from breaking through rather than from killing things, which is what the
system was always about, and the pills carry real weight: each one is a third of
your ceiling rather than a permission slip.

Each stage passive is carried by the status its drink applies, so a stage is
reached by drinking and cannot be reached any other way. The tier's nine
containers are unlocked by the passive itself, which means an over-stage
technique is not merely forbidden - it is absent. Nothing to check at cast time.

Your spellbook visibly grows at each breakthrough: 9 containers -> 18 -> 27.
"""
import os

PATHS = ["Water", "Fire", "Earth", "Metal", "Wood",
         "Poison", "Acid", "Lightning", "Wind"]

# (passive, tier it unlocks, Essence and Attunement it adds)
STAGES = [
    ("EssenceDao_Cultivator", "Initiate", 8),
    ("EssenceDao_Breakthrough_Foundation", "Adept", 8),
    ("EssenceDao_Breakthrough_GoldenCore", "Master", 8),
]

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "..", "Public", "EssenceDao", "Stats", "Generated", "Data",
                   "Passive.txt")


import json

# gen_abilities.py writes the exact container list, including any path it had to
# split for size. Reading it means the two files cannot drift.
CONTAINERS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                          "Public", "EssenceDao", "Stats", "Generated",
                          "containers.json")
with open(CONTAINERS, encoding="utf-8") as fh:
    PATH_CONTAINERS = json.load(fh)


lines = [
    "// ============================================================",
    "//  Essence Dao - the three cultivation stages",
    "//  GENERATED by build/gen_pool_passives.py - do not edit by hand",
    "// ============================================================",
    "",
]

running = 0
for name, tier, gain in STAGES:
    running += gain
    boosts = [f"ActionResource(EssencePoint,{gain},0)",
              f"ActionResource(EssenceAttunement,{gain},0)"]
    if name == "EssenceDao_Cultivator":
        # Every path container, once, at the first stage. Breaking through no
        # longer adds icons to your spellbook - it unlocks entries *inside* the
        # containers you already have, via the stage conditions on each. So the
        # spellbook stops growing after the first elixir.
        boosts += [f"UnlockSpell({c})" for c in PATH_CONTAINERS]
        boosts += ["UnlockSpell(Shout_EssenceDao_SetAside)"]
    lines += [
        f'new entry "{name}"',
        'type "PassiveData"',
        f'data "DisplayName" "h{name}Name;1"',
        f'data "Description" "h{name}Desc;1"',
        f'data "DescriptionParams" "{running}"',
        'data "Icon" "PassiveFeature_Generic_Magical"',
        'data "Properties" "Highlighted"',
        f'data "Boosts" "{";".join(boosts)}"',
        "",
    ]

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))

print(f"wrote {os.path.normpath(OUT)}")
total = 0
for name, tier, gain in STAGES:
    total += gain
    print(f"  {name:<36} +{gain} Essence -> {total:>2}   unlocks {tier}")
print(f"  {len(PATHS)} paths x {len(STAGES)} stages = {len(PATHS)*len(STAGES)} containers")
