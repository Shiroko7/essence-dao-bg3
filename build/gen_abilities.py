# -*- coding: utf-8 -*-
"""Generate every technique stat entry from build/defs/*.py.

Emits, per technique:
  * a learned passive        EssenceDao_T_<Path>_<Name>
  * for actives, the spell   <Type>_EssenceDao_<Path>_<Name>
  * a learn-spell            Shout_EssenceDao_Learn_<Path>_<Name>

plus the 27 path containers and every custom status.

Learn-spells are what appear inside a container. Casting one binds the technique
permanently: it costs EssenceAttunement (so BG3 greys out what you cannot
afford) and applies the learned passive. The passive is what actually does the
work, and it carries the negative resource boosts that make the cost permanent.

Run: python build/gen_abilities.py
"""
import importlib, os, pkgutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from defs._schema import (all_abilities, all_statuses, all_raw_spells,  # noqa: E402
                          PATHS, TIERS)

# import every definition module so the registries fill
import defs                                                        # noqa: E402
for _, modname, _ in pkgutil.iter_modules(defs.__path__):
    if not modname.startswith("_"):
        importlib.import_module(f"defs.{modname}")

OUT = os.path.join(ROOT, "Public", "EssenceDao", "Stats", "Generated", "Data")

# A distinct icon per path, all lifted from Larian's own stats. Previously every
# container and every entry used PassiveFeature_Generic_Magical - 724 of 1,035
# icon fields were that one string, which is why the spellbook was unreadable.
PATH_ICON = {
    "Water":     "Action_ElementalWildShape_Myrmidon_Water",
    "Fire":      "Action_ElementalWildShape_Myrmidon_Fire",
    "Earth":     "Action_ElementalWildShape_Myrmidon_Earth",
    "Metal":     "Spell_Transmutation_HeatMetal",
    "Wood":      "Spell_Conjuration_ConjureWoodlandBeings",
    "Poison":    "Action_Dragonborn_BreathWeapon_Poison",
    "Acid":      "Action_Dragonborn_BreathWeapon_Acid",
    "Lightning": "Action_Dragonborn_BreathWeapon_Lightning",
    "Wind":      "Action_Monster_ElementalAir_Whirlwind",
}

# Which cultivation status a tier requires. Gating used to be structural - each
# tier had its own container, unlocked by its stage passive - but that meant 27
# top-level spellbook entries at Master. Now there is one container per path and
# the gate is a condition, so over-stage techniques are visible but greyed. You
# can see what is ahead of you, which the old arrangement could not show.
TIER_STATUS = {
    "initiate": None,
    "adept":    "ESSDAO_FOUNDATION_TAKEN",
    "master":   "ESSDAO_GOLDENCORE_TAKEN",
}

# Larian's largest container holds 32 children (median 5). A path with more than
# this is split rather than gambling on untested UI behaviour.
MAX_CONTAINER = 32

# Most techniques never got an icon of their own, so they fell back to one
# generic string - 65% of every icon field in the mod was the same image, which
# is why the spellbook was unreadable. Anything still on the generic gets its
# path's icon instead: not unique, but at least you can tell a Fire technique
# from a Poison one at a glance.
GENERIC_ICON = "PassiveFeature_Generic_Magical"


def icon_for(a):
    return PATH_ICON.get(a.path, GENERIC_ICON) if a.icon == GENERIC_ICON else a.icon

# Every spell needs a SpellAnimation or the engine complains:
#     !ASSERT!Design: Spell prototype 'X' has no cast animations.
# Rather than author any, we reuse the animation set Larian uses most often for
# each spell type - harvested from the shipped stats into spell_animations.json.
# A Zone spell then casts like Larian's Zone spells, which is what we want.
import json as _json
ANIM = _json.load(open(os.path.join(HERE, "spell_animations.json"), encoding="utf-8"))
os.makedirs(OUT, exist_ok=True)

abilities = all_abilities()
statuses = all_statuses()


def entry(name, etype, fields):
    out = [f'new entry "{name}"', f'type "{etype}"']
    for k, v in fields.items():
        if v == "" or v is None:
            continue
        out.append(f'data "{k}" "{v}"')
    out.append("")
    return out


# ---------------------------------------------------------------- passives ---
plines = ["// GENERATED by build/gen_abilities.py - do not edit by hand", ""]
for a in abilities:
    f = {
        "DisplayName": f"{a.h_name};1",
        "Description": f"{a.h_desc};1",
        "Icon": icon_for(a),
        "Properties": a.passive_properties or "Highlighted",
        "Boosts": a.learned_boosts(),
    }
    # raw PassiveData fields (StatsFunctorContext / Conditions / StatsFunctors)
    if a.kind == "passive":
        f.update(a.fields)
    plines += entry(a.passive_name, "PassiveData", f)

with open(os.path.join(OUT, "Passive_Techniques.txt"), "w",
          encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(plines))

# ------------------------------------------------------------------ spells ---
by_type = {}
for a in abilities:
    if a.kind != "active":
        continue
    f = {"SpellType": a.spell_type}
    f.update(a.fields)
    f.setdefault("DisplayName", f"{a.h_name};1")
    f.setdefault("Description", f"{a.h_desc};1")
    f.setdefault("Level", "0")
    f.setdefault("SpellSchool", "Evocation")
    f.setdefault("PreviewCursor", "Cast")
    f.setdefault("CastTextEvent", "Cast")
    f.setdefault("SpellStyleGroup", "Class")
    if a.spell_type in ANIM:
        f.setdefault("SpellAnimation", ANIM[a.spell_type])
    by_type.setdefault(a.spell_type, []).append(entry(a.spell_name, "SpellData", f))

# ------------------------------------------------------------ learn-spells ---
# Each technique is ONE entry that toggles: bind it if you do not hold it,
# release it if you do. `IF(cond):Functor` is Larian's own syntax - 201 uses in
# shipped SpellProperties, including IF(...):RemoveStatus.
#
# This replaced a parallel tree of nine Release containers holding every
# technique of every tier. Those were half the spellbook, they listed things you
# had never bound, and clicking one of those did nothing at all - which is
# exactly what a player reported.
#
# A toggle cannot be a no-op: whichever state you are in, one branch fires.
learn = []
for a in abilities:
    st = f"ESSDAO_LEARN_{a.slug.upper()}"
    have = f"HasStatus('{st}',context.Source)"
    stage = TIER_STATUS[a.tier]

    # Affordability OR already-bound: you must always be able to let go of
    # something, including a technique from a stage you can no longer reach.
    cond = (f"Self() and ({have} or HasActionResource('EssenceAttunement',"
            f"{a.cost},0,false,false,context.Source))")
    if stage:
        cond += f" and ({have} or HasStatus('{stage}',context.Source))"

    learn.append(entry(a.learn_name, "SpellData", {
        "SpellType": "Shout",
        "Level": "0",
        "SpellSchool": "Transmutation",
        # -1 duration = permanent. The status carries the technique passive.
        # No UseCosts: the learned passive's negative boost is the only
        # accounting - it lowers max Attunement, and because the resource
        # replenishes on rest, current always settles to that same max.
        "SpellProperties": (f"IF(not {have}):ApplyStatus(SELF,{st},100,-1);"
                            f"IF({have}):RemoveStatus(SELF,{st})"),
        "TargetConditions": cond,
        "Requirements": "!Combat",
        "SpellFlags": "IsSpell",
        "VerbalIntent": "Utility",
        "Icon": icon_for(a),
        "DisplayName": f"{a.h_learn_name};1",
        "Description": f"{a.h_learn_desc};1",
        "PreviewCursor": "Cast",
        "CastTextEvent": "Cast",
        "SpellStyleGroup": "Class",
        "SpellAnimation": ANIM["Shout"],
    }))

# The learn-spell applies a permanent status whose Passives field grants the
# technique. Going through a status rather than calling AddPassive keeps the
# whole thing inside the stats system - no scripting needed to learn anything.
learn_statuses = []
for a in abilities:
    learn_statuses.append(entry(f"ESSDAO_LEARN_{a.slug.upper()}", "StatusData", {
        "StatusType": "BOOST",
        "DisplayName": f"{a.h_name};1",
        "Description": f"{a.h_desc};1",
        "Icon": icon_for(a),
        "Passives": a.passive_name,
        # Deliberately visible now. These used to carry DisableOverhead and
        # DisableCombatlog "to avoid clutter", with the result that binding a
        # technique produced no feedback whatsoever and looked broken. The
        # overhead text and combat-log line are the only confirmation the player
        # gets that anything happened.
        "StatusPropertyFlags": "IgnoreResting",
        "StatusGroups": "SG_RemoveOnRespec",
        # A bound technique cannot outlive the cultivation that holds it. This
        # pair is Larian's own idiom - Bladesong's sub-statuses carry exactly
        # `not HasStatus('BLADESONG')` + `OnStatusRemoved` - and it is what lets
        # "set the Dao aside" be a single RemoveStatus.
        #
        # It replaced a spell that listed all 122 techniques by name in one
        # SpellProperties string: 11,344 characters, against 4,052 for the
        # largest Larian ships. build/check_field_sizes.py now guards that.
        "RemoveConditions": "not HasStatus('ESSDAO_CULTIVATOR')",
        "RemoveEvents": "OnStatusRemoved",
        "StackId": f"ESSDAO_LEARN_{a.slug.upper()}",
        "TickType": "None",
    }))

# There are no release-spells and no release containers any more - the toggle
# above does both jobs. That removed nine top-level entries and every dead click.
release = []
release_containers = []

# ------------------------------------------------- technique-granted spells ---
for name, stype, f in all_raw_spells():
    f = {"SpellType": stype, **f}
    f.setdefault("SpellStyleGroup", "Class")
    if stype in ANIM:
        f.setdefault("SpellAnimation", ANIM[stype])
    by_type.setdefault(stype, []).append(entry(name, "SpellData", f))

# -------------------------------------------------------------- containers ---
# One container per path, holding every tier, ordered Initiate -> Master.
#
# It used to be one per path *and tier*: nine icons at Initiate, eighteen at
# Adept, twenty-seven at Master, plus nine Release containers and Set the Dao
# Aside - thirty-seven top-level entries in a spellbook section we cannot even
# name. Now it is nine (or ten, where a path splits), and that number never
# grows. Stage gating moved onto the entries themselves.
containers = []
container_names = []
TIER_ORDER = {t.lower(): i for i, t in enumerate(TIERS)}
for path in PATHS:
    members = sorted((a for a in abilities if a.path == path),
                     key=lambda a: (TIER_ORDER.get(a.tier, 9), a.name))
    # Split only where a path exceeds what Larian's own UI is known to carry,
    # and split *evenly* - a naive slice gave Wood 32 and 2, which reads as a
    # bug rather than a division.
    import math
    n_chunks = max(1, math.ceil(len(members) / MAX_CONTAINER))
    size = max(1, math.ceil(len(members) / n_chunks))
    chunks = [members[i:i + size] for i in range(0, len(members), size)] or [[]]
    for n, chunk in enumerate(chunks):
        name = f"Shout_EssenceDao_{path}" + (f"_{n + 1}" if len(chunks) > 1 else "")
        suffix = f" ({n + 1}/{len(chunks)})" if len(chunks) > 1 else ""
        container_names.append(name)
        containers.append(entry(name, "SpellData", {
            "SpellType": "Shout",
            "Level": "0",
            "SpellSchool": "Transmutation",
            "ContainerSpells": ";".join(m.learn_name for m in chunk),
            "TargetConditions": "Self()",
            "Requirements": "!Combat",
            "SpellFlags": "IsLinkedSpellContainer;IsSpell",
            "VerbalIntent": "Utility",
            "Icon": PATH_ICON[path],
            "DisplayName": f"hEssDaoP_{path}{'_' + str(n + 1) if len(chunks) > 1 else ''}_Name;1",
            "Description": f"hEssDaoP_{path}_Desc;1",
            "PreviewCursor": "Cast",
            "CastTextEvent": "Cast",
            "SpellStyleGroup": "Class",
            "SpellAnimation": ANIM["Shout"],
        }))

# gen_pool_passives.py needs to know exactly what to unlock.
with open(os.path.join(OUT, "..", "containers.json"), "w", encoding="utf-8") as fh:
    _json.dump(container_names, fh, indent=1)

# ---------------------------------------------------------------- statuses ---
slines = ["// GENERATED by build/gen_abilities.py - do not edit by hand", ""]
for s in statuses:
    f = {"StatusType": s.stype,
         "DisplayName": f"{s.h_name};1",
         "Description": f"{s.h_desc};1"}
    f.update(s.fields)
    slines += entry(s.name, "StatusData", f)
for blk in learn_statuses:
    slines += blk

with open(os.path.join(OUT, "Status_BOOST.txt"), "w",
          encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(slines))

# ------------------------------------------------------------------ output ---
shout = ["// GENERATED by build/gen_abilities.py - do not edit by hand", ""]
for blk in containers:
    shout += blk
for blk in learn:
    shout += blk
for blk in release_containers:
    shout += blk
for blk in release:
    shout += blk
for blk in by_type.pop("Shout", []):
    shout += blk
with open(os.path.join(OUT, "Spell_Shout.txt"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(shout))

for stype, blocks in by_type.items():
    lines = ["// GENERATED by build/gen_abilities.py - do not edit by hand", ""]
    for blk in blocks:
        lines += blk
    with open(os.path.join(OUT, f"Spell_{stype}.txt"), "w",
              encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))

# ------------------------------------------------------------------ report ---
from collections import Counter
print(f"abilities   : {len(abilities)}")
print(f"  passive   : {sum(1 for a in abilities if a.kind=='passive')}")
print(f"  active    : {sum(1 for a in abilities if a.kind=='active')}")
print(f"statuses    : {len(statuses)} custom + {len(abilities)} learn-markers")
print(f"containers  : {len(containers)}")
print()
per = Counter(a.path for a in abilities)
for p in PATHS:
    tiers = Counter(a.tier for a in abilities if a.path == p)
    print(f"  {p:<10} {per[p]:>3}   "
          + "  ".join(f"{t}={tiers[t]}" for t in ('initiate', 'adept', 'master')))
