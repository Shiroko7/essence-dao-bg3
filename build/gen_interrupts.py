# -*- coding: utf-8 -*-
"""The four real interrupts.

Four techniques are reactions in the true sense - they fire on someone else's
roll, not on your turn - so they need Interrupt entries rather than castable
spells. Format copied from Larian's Interrupt_HellishRebuke.

InterruptContext values are fixed by the engine; the complete list is
None / OnSpellCast / OnPostRoll / OnCastHit / OnEnterAttackRange /
OnLeaveAttackRange / OnPreDamage / OnStatusApplied / OnDeath.

    Glacial Shield         OnPreDamage   spend a slot for temporary hit points
    Ember's Resilience     OnPostRoll    reroll a failed save, take 2d6 fire
    Misty Escape           OnPreDamage   spend a slot to turn a hit into a miss
    Whispers of the Gale   OnPostRoll    reroll a missed ranged attack
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DATA = os.path.join(ROOT, "Public", "EssenceDao", "Stats", "Generated", "Data")

INTERRUPTS = [
    dict(
        name="Interrupt_EssenceDao_GlacialShield",
        handle="hEssDaoI_GlacialShield",
        icon="Spell_Abjuration_ArmorOfAgathys",
        context="OnPreDamage",
        scope="Self",
        container="YesNoDecision",
        conditions="IsAbleToReact(context.Observer) and not Dead(context.Observer)",
        properties="ApplyStatus(OBSERVER,ESSDAO_GLACIALSHIELD_TEMPHP,100,100)",
        cost="ReactionActionPoint:1;SpellSlotsGroup:1:1:1",
        stack="EssenceDaoGlacialShield",
    ),
    dict(
        name="Interrupt_EssenceDao_EmbersResilience",
        handle="hEssDaoI_EmbersResilience",
        icon="PassiveFeature_Generic_Fire",
        context="OnPostRoll",
        scope="Self",
        container="YesNoDecision",
        # Only worth offering on a save you actually failed.
        conditions="IsSavingThrow() and not IsCritical() and RollResultIsLowerThan(1) "
                   "and IsAbleToReact(context.Observer)",
        properties="Reroll(1,true);DealDamage(OBSERVER,2d6,Fire,Magical)",
        cost="ReactionActionPoint:1;EssencePoint:2",
        stack="EssenceDaoEmbersResilience",
    ),
    dict(
        name="Interrupt_EssenceDao_MistyEscape",
        handle="hEssDaoI_MistyEscape",
        icon="Spell_Transmutation_GaseousForm",
        context="OnPreDamage",
        scope="Self",
        container="YesNoDecision",
        conditions="IsAbleToReact(context.Observer) and not Dead(context.Observer) "
                   "and HasDamageEffectFlag(DamageFlags.Hit)",
        properties="ApplyStatus(OBSERVER,ESSDAO_MISTYESCAPE,100,1)",
        cost="ReactionActionPoint:1;SpellSlotsGroup:1:1:1",
        stack="EssenceDaoMistyEscape",
    ),
    dict(
        name="Interrupt_EssenceDao_WhispersOfTheGale",
        handle="hEssDaoI_WhispersOfTheGale",
        icon="Spell_Divination_Portent",
        context="OnPostRoll",
        scope="Self",
        container="YesNoDecision",
        conditions="IsAttack() and IsRangedAttack() and IsMiss() "
                   "and IsAbleToReact(context.Observer)",
        properties="Reroll(Attack,1,true)",
        cost="ReactionActionPoint:1;SpellSlotsGroup:1:1:1",
        stack="EssenceDaoWhispersOfTheGale",
    ),
]

lines = ["// GENERATED by build/gen_interrupts.py - do not edit by hand", ""]
for i in INTERRUPTS:
    lines += [
        f'new entry "{i["name"]}"',
        'type "InterruptData"',
        f'data "DisplayName" "{i["handle"]}_Name;1"',
        f'data "Description" "{i["handle"]}_Desc;1"',
        f'data "Icon" "{i["icon"]}"',
        f'data "InterruptContext" "{i["context"]}"',
        f'data "InterruptContextScope" "{i["scope"]}"',
        f'data "Container" "{i["container"]}"',
        f'data "Conditions" "{i["conditions"]}"',
        f'data "Properties" "{i["properties"]}"',
        f'data "Cost" "{i["cost"]}"',
        f'data "Stack" "{i["stack"]}"',
        'data "InterruptDefaultValue" "Enabled;Ask"',
        "",
    ]

with open(os.path.join(DATA, "Interrupt.txt"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))

# supporting statuses
st = ["// GENERATED by build/gen_interrupts.py - do not edit by hand", ""]
st += [
    'new entry "ESSDAO_GLACIALSHIELD_TEMPHP"',
    'type "StatusData"',
    'data "StatusType" "BOOST"',
    'data "DisplayName" "hEssDaoI_GlacialShield_Name;1"',
    'data "Description" "hEssDaoI_GlacialShield_Desc;1"',
    'data "Icon" "Spell_Abjuration_ArmorOfAgathys"',
    'data "StatusPropertyFlags" "IgnoreResting"',
    'data "StatusGroups" "SG_RemoveOnRespec"',
    'data "StackId" "ESSDAO_GLACIALSHIELD_TEMPHP"',
    'data "TickType" "EndTurn"',
    'data "OnApplyFunctors" "RegainTemporaryHitPoints(10+SpellCastingAbilityModifier)"',
    "",
    'new entry "ESSDAO_MISTYESCAPE"',
    'type "StatusData"',
    'data "StatusType" "BOOST"',
    'data "DisplayName" "hEssDaoI_MistyEscape_Name;1"',
    'data "Description" "hEssDaoI_MistyEscape_Desc;1"',
    'data "Icon" "Spell_Transmutation_GaseousForm"',
    'data "StatusPropertyFlags" "IgnoreResting"',
    'data "StatusGroups" "SG_RemoveOnRespec"',
    'data "Boosts" "DamageReduction(All,Half);Resistance(All,Resistant)"',
    'data "StackId" "ESSDAO_MISTYESCAPE"',
    'data "TickType" "EndTurn"',
    "",
]
with open(os.path.join(DATA, "Status_BOOST_Interrupts.txt"), "w",
          encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(st))

print(f"wrote {len(INTERRUPTS)} interrupts + 2 supporting statuses")
for i in INTERRUPTS:
    print(f"  {i['name']:<44} {i['context']}")
